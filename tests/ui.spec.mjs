import { test, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
test('two team sessions, calendars, actuals, settings, and mobile layout', async ({ page, browser }) => {
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await mkdir('test-results/screenshots', { recursive: true });
  await page.setViewportSize({ width: 1440, height: 1050 });
  await page.goto('/');
  await expect(page.getByRole('heading', { name: '첫 관리자 등록' })).toBeVisible();
  await page.screenshot({ path: 'test-results/screenshots/setup-desktop.png', fullPage: true });
  await page.locator('#auth-form [name=name]').fill('검증 관리자');
  await page.locator('#auth-form [name=login]').fill('testadmin');
  await page.locator('#auth-form [name=password]').fill('test-only-password-123');
  await page.locator('#auth-submit').click();
  await expect(page.locator('.schedule-table tbody tr')).toHaveCount(6);
  await page.locator('#date-picker').fill('2026-10-12');
  await page.locator('#date-picker').dispatchEvent('change');
  await expect(page.locator('#period-title')).toContainText('12일');
  await page.locator('[data-page=settings]').click();
  await page.locator('#add-user').click();
  await page.locator('#user-form [name=name]').fill('검증 담당자');
  await page.locator('#user-form [name=login]').fill('testmember');
  await page.locator('#user-form [name=password]').fill('test-member-password-123');
  await page.locator('#user-form [type=submit]').click();
  await expect(page.locator('#modal')).not.toBeVisible();
  const second = await browser.newContext({ timezoneId: 'Asia/Seoul' });
  const page2 = await second.newPage(); await page2.goto('/');
  await page2.locator('#auth-form [name=login]').fill('testmember');
  await page2.locator('#auth-form [name=password]').fill('test-member-password-123');
  await page2.locator('#auth-submit').click();
  await expect(page2.locator('.schedule-table')).toBeVisible();
  await page.locator('[data-page=schedule]').click();
  await page.locator('#new-test').click();
  await page.locator('#reservation-form [name=title]').fill('열피로 연속시험 검증');
  await page.locator('#reservation-form [name=equipmentId]').selectOption('thermal-1');
  await page.locator('#reservation-form [name=testType]').selectOption('열피로 시험');
  await page.locator('#reservation-form [name=start]').fill('2026-10-12T08:30');
  await page.locator('#reservation-form [name=end]').fill('2026-10-14T20:30');
  await page.locator('#reservation-form [name=status]').selectOption('진행');
  await page.locator('#reservation-form [type=submit]').click();
  await expect(page.locator('#modal')).not.toBeVisible();
  await expect(page.locator('.booking')).toHaveCount(3);
  await page2.locator('#date-picker').fill('2026-10-12'); await page2.locator('#date-picker').dispatchEvent('change');
  await expect(page2.locator('.booking')).toHaveCount(3);
  await page.locator('#new-test').click();
  await page.locator('#reservation-form [name=title]').fill('中복 예약 검증');
  await page.locator('#reservation-form [name=equipmentId]').selectOption('thermal-1');
  await page.locator('#reservation-form [name=start]').fill('2026-10-12T09:30');
  await page.locator('#reservation-form [name=end]').fill('2026-10-12T10:30');
  await page.locator('#reservation-form [type=submit]').click();
  await expect(page.locator('#reservation-form .error')).toContainText('중복');
  await page.locator('#close-modal').click();
  await page.locator('.booking').first().click();
  await page.locator('[data-actual]').click();
  await page.locator('#actual-form [type=submit]').click();
  await expect(page.locator('#modal')).not.toBeVisible();
  await page.locator('[data-page=capacity]').click();
  await expect(page.locator('.capacity-table')).toBeVisible();
  await expect(page.locator('.capacity-table tr').filter({ hasText: '열가진 내구시험실 #1' })).toContainText('36');
  await page.screenshot({ path: 'test-results/screenshots/capacity-desktop.png', fullPage: true });
  await page.locator('[data-page=history]').click(); await page.locator('#save-baseline').click();
  await expect(page.locator('.baseline-item')).toHaveCount(1);
  await page.locator('[data-page=schedule]').click();
  await page.screenshot({ path: 'test-results/screenshots/schedule-desktop.png', fullPage: true });
  await page.locator('[data-mode=month]').click(); await expect(page.locator('.month-table thead th')).toHaveCount(32);
  await page.locator('[data-mode=day]').click(); await expect(page.locator('.day-table thead th')).toHaveCount(49);
  await page.locator('[data-mode=week]').click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/screenshots/schedule-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await page.locator('#new-test').click(); await expect(page.locator('#modal')).toBeVisible();
  expect(await page.locator('#modal').evaluate(e => e.getBoundingClientRect().right <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/screenshots/form-mobile.png', fullPage: true });
  expect(errors).toEqual([]);
  await second.close();
});
