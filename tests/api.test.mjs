import test from 'node:test';
import assert from 'node:assert/strict';
import { createApp } from '../server.mjs';
import XLSX from 'xlsx';
test('setup, authentication, csrf, reservation validation, and export', async () => {
  const { server, store } = createApp({ dbPath: ':memory:' });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  let cookie = '', csrf = '';
  const request = async (path, method = 'GET', body, useCsrf = true) => {
    const res = await fetch(base + path, { method, headers: { 'content-type': 'application/json', origin: base, cookie, ...(useCsrf ? { 'x-csrf-token': csrf } : {}) }, body: body ? JSON.stringify(body) : undefined });
    if (res.headers.get('set-cookie')) cookie = res.headers.get('set-cookie').split(';')[0];
    return res;
  };
  try {
    assert.equal((await request('/api/reservations', 'POST', {})).status, 401);
    let res = await request('/api/setup', 'POST', { login: 'manager', name: '관리자', password: 'test-password-123' });
    assert.equal(res.status, 201);
    const account = await res.json(); csrf = account.csrf;
    assert.equal((await request('/api/users', 'POST', { login: 'member', name: '담당자', password: 'another-password' }, false)).status, 403);
    const booking = { title: '검증 예약', equipmentId: 'engine-1', testType: '배압 시험', ownerId: account.user.id, start: '2026-10-12T08:30:00+09:00', end: '2026-10-12T09:30:00+09:00', status: '계획' };
    assert.equal((await request('/api/reservations', 'POST', booking)).status, 201);
    const duplicate = await request('/api/reservations', 'POST', booking);
    assert.equal(duplicate.status, 409);
    assert.equal((await duplicate.json()).code, 'DUPLICATE_BOOKING');
    assert.equal((await request('/api/reservations', 'POST', { ...booking, equipmentId: 'wrong' })).status, 400);
    const exported = await request('/api/export?start=2026-10-01T00:00:00%2B09:00&end=2026-11-01T00:00:00%2B09:00');
    assert.equal(exported.headers.get('content-type'), 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet');
    const workbook = XLSX.read(Buffer.from(await exported.arrayBuffer()), { type: 'buffer' });
    const values = XLSX.utils.sheet_to_json(workbook.Sheets['시험계획']);
    assert.equal(values[0].시험명, '검증 예약');
    const dt = XLSX.SSF.parse_date_code(values[0].시작);
    assert.equal(dt.H, 8); assert.equal(dt.M, 30); assert.equal(dt.d, 12);
    assert.equal((await request('/api/setup', 'POST', {})).status, 409);
    assert.equal((await request('/api/state')).status, 200);
    const current = store.reservations()[0];
    const capacityPath = '/api/capacity?start=2026-10-12T00:00:00%2B09:00&end=2026-10-13T00:00:00%2B09:00';
    const engine = async () => (await (await request(capacityPath)).json()).find(e => e.id === 'engine-1');
    assert.equal((await engine()).originalPlanMinutes, 60);
    assert.equal((await engine()).originalMissingActuals, 1);
    const changed = store.saveReservation({ ...current, end: '2026-10-12T10:30:00+09:00', reason: '기간 연장' }, account.user.id, current.id);
    store.saveActual({ reservationId: changed.id, start: changed.start, end: changed.end }, account.user.id);
    let comparison = await engine();
    assert.equal(comparison.originalPlanMinutes, 60);
    assert.equal(comparison.plannedMinutes, 120);
    assert.equal(comparison.actualMinutes, 120);
    assert.equal(comparison.originalAchievementPercent, 200);
    const state = await (await request('/api/state')).json();
    assert.equal(state.actuals.find(a => a.reservationId === changed.id).intervals[0].start, changed.start);
    assert.equal(comparison.originalMissingActuals, 0);
    const zero = store.saveReservation({ ...booking, start: changed.end, end: '2026-10-12T11:30:00+09:00' }, account.user.id);
    store.saveActual({ reservationId: zero.id, zero: true, note: '미실시' }, account.user.id);
    comparison = await engine();
    assert.equal(comparison.originalPlanMinutes, 120);
    assert.equal(comparison.originalMissingActuals, 0);
    assert.equal(comparison.originalAchievementPercent, 100);
    assert.deepEqual((await (await request('/api/state')).json()).actuals.find(a => a.reservationId === zero.id).intervals, []);
    const cancelled = store.saveReservation({ ...booking, start: zero.end, end: '2026-10-12T12:30:00+09:00' }, account.user.id);
    store.saveReservation({ ...cancelled, status: '취소', reason: '시험 취소' }, account.user.id, cancelled.id);
    comparison = await engine();
    assert.equal(comparison.originalPlanMinutes, 180);
    assert.equal(comparison.originalMissingActuals, 0);
    store.saveReservation({ ...booking, equipmentId: 'engine-2', start: '2026-10-09T08:30:00+09:00', end: '2026-10-12T09:30:00+09:00' }, account.user.id);
    const weekend = (await (await request('/api/capacity?start=2026-10-10T00:00:00%2B09:00&end=2026-10-11T00:00:00%2B09:00')).json()).find(e => e.id === 'engine-2');
    assert.equal(weekend.originalPlanMinutes, 0);
    assert.equal(weekend.originalMissingActuals, 0);
    assert.equal(weekend.originalAchievementPercent, null);
    assert.equal((await request('/api/actuals/' + changed.id, 'DELETE', undefined, false)).status, 403);
    assert.equal((await request('/api/actuals/not-found', 'DELETE')).status, 404);
    assert.equal((await request('/api/actuals/' + changed.id, 'DELETE')).status, 200);
    assert.equal(store.reservation(changed.id).title, changed.title);
    assert.equal(store.reservation(changed.id).version, changed.version);
    comparison = await engine();
    assert.equal(comparison.actualMinutes, 0);
    assert.equal(comparison.originalPlanMinutes, 180);
    assert.equal(comparison.originalMissingActuals, 1);
    assert.equal((await request('/api/actuals/' + zero.id, 'DELETE')).status, 200);
    assert.equal((await request('/api/actuals/' + zero.id, 'DELETE')).status, 404);
    assert.equal((await engine()).originalMissingActuals, 2);
    const equipment = await (await request('/api/equipment')).json();
    for (const id of ['engine-1', 'engine-2']) assert.deepEqual(equipment.find(e => e.id === id).types, ['배압 시험', '토출/방사음 시험']);
    for (const id of ['thermal-1', 'thermal-2']) assert.ok(equipment.find(e => e.id === id).types.includes('기타 성능시험'));
    const concurrent = { ...booking, includeWeekend: true, start: '2026-10-10T08:30:00+09:00', end: '2026-10-10T09:30:00+09:00' };
    const paired = [];
    for (const testType of ['배압 시험', '토출/방사음 시험']) {
      const response = await request('/api/reservations', 'POST', { ...concurrent, testType });
      assert.equal(response.status, 201); paired.push(await response.json());
    }
    assert.equal((await request('/api/reservations', 'POST', concurrent)).status, 409);
    for (const r of paired) assert.equal((await request('/api/actuals', 'POST', { reservationId: r.id, start: r.start, end: r.end })).status, 200);
    const combined = (await (await request('/api/capacity?start=2026-10-10T00:00:00%2B09:00&end=2026-10-11T00:00:00%2B09:00')).json()).find(e => e.id === 'engine-1');
    assert.equal(combined.plannedMinutes, 60); assert.equal(combined.actualMinutes, 60);
    assert.equal(combined.originalPlanMinutes, 60); assert.equal(combined.originalAchievementPercent, 100);
  } finally { await new Promise(resolve => server.close(resolve)); store.db.close(); }
});
